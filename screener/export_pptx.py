"""One-slide summary for the deal team in a fixed style (navy / orange)."""
from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt

NAVY = RGBColor(0x14, 0x28, 0x4B)
ACCENT = RGBColor(0xE8, 0xA3, 0x3D)
GREY = RGBColor(0x3F, 0x3F, 0x3F)
LIGHT = RGBColor(0xEE, 0xF2, 0xF8)
COLORS = {"fit": RGBColor(0x2E, 0x8B, 0x57), "maybe": RGBColor(0xD9, 0x9A, 0x00), "no_fit": RGBColor(0xC0, 0x39, 0x2B)}


def _text(slide, x, y, w, h, text, size=12, bold=False, color=GREY, align=PP_ALIGN.LEFT):
    tb = slide.shapes.add_textbox(x, y, w, h)
    tf = tb.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text, p.alignment = text, align
    p.font.size, p.font.bold, p.font.color.rgb = Pt(size), bold, color
    return tb


def export_pptx(path, companies, results, mandate, top_n=5):
    by_id = {c.company_id: c for c in companies}
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(13.333), Inches(7.5)
    s = prs.slides.add_slide(prs.slide_layouts[6])

    bar = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, prs.slide_width, Inches(1.1))
    bar.fill.solid(); bar.fill.fore_color.rgb = NAVY; bar.line.fill.background()
    line = s.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, Inches(1.1), prs.slide_width, Inches(0.06))
    line.fill.solid(); line.fill.fore_color.rgb = ACCENT; line.line.fill.background()
    _text(s, Inches(0.5), Inches(0.18), Inches(12), Inches(0.5),
          f"Target screening – mandate {mandate['mandate_id']}", 26, True, RGBColor(255, 255, 255))
    _text(s, Inches(0.5), Inches(0.65), Inches(12), Inches(0.4), mandate["target_profile"], 13, False, ACCENT)

    # KPI boxes
    for i, lab in enumerate(["fit", "maybe", "no_fit"]):
        n = sum(r.label == lab for r in results)
        x = Inches(0.5 + i * 2.2)
        box = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, x, Inches(1.5), Inches(2.0), Inches(1.3))
        box.fill.solid(); box.fill.fore_color.rgb = LIGHT; box.line.color.rgb = COLORS[lab]
        _text(s, x, Inches(1.6), Inches(2.0), Inches(0.7), str(n), 32, True, COLORS[lab], PP_ALIGN.CENTER)
        _text(s, x, Inches(2.25), Inches(2.0), Inches(0.4), lab.replace("_", " ").upper(), 12, True, NAVY, PP_ALIGN.CENTER)
    _text(s, Inches(7.3), Inches(1.6), Inches(5.6), Inches(1.2),
          f"{len(results)} companies screened against hard criteria (country, sector, revenue, owner) "
          f"and soft criteria (margin, growth, size). Red flags are sent for review.", 13)

    # Top targets table
    fits = sorted([r for r in results if r.label == "fit"], key=lambda r: -r.score)[:top_n]
    _text(s, Inches(0.5), Inches(3.05), Inches(8), Inches(0.4), f"Top {len(fits)} targets", 16, True, NAVY)
    rows, cols = len(fits) + 1, 6
    tbl = s.shapes.add_table(rows, cols, Inches(0.5), Inches(3.5), Inches(12.3), Inches(0.4 * rows)).table
    heads = ["Company", "Country", "Sector", "Revenue (EUR m)", "EBITDA margin", "Growth"]
    widths = [4.3, 1.2, 2.4, 1.5, 1.5, 1.4]
    for j, (h, w) in enumerate(zip(heads, widths)):
        tbl.columns[j].width = Inches(w)
        cell = tbl.cell(0, j)
        cell.text = h
        cell.fill.solid(); cell.fill.fore_color.rgb = NAVY
        para = cell.text_frame.paragraphs[0]
        para.font.bold, para.font.size, para.font.color.rgb = True, Pt(12), RGBColor(255, 255, 255)
    for i, r in enumerate(fits, start=1):
        c = by_id[r.company_id]
        vals = [c.name, c.country, c.sector, f"{c.revenue_eur_m:.1f}", f"{c.ebitda_margin:.0%}", f"{c.revenue_growth:.0%}"]
        for j, v in enumerate(vals):
            cell = tbl.cell(i, j)
            cell.text = v
            cell.text_frame.paragraphs[0].font.size = Pt(12)
            cell.fill.solid(); cell.fill.fore_color.rgb = LIGHT if i % 2 else RGBColor(255, 255, 255)

    _text(s, Inches(0.5), Inches(7.0), Inches(12.3), Inches(0.3),
          "Fictional sample data · generated by mna-company-screener", 9, False, RGBColor(0x7A, 0x84, 0x99))
    prs.save(path)
    return path
